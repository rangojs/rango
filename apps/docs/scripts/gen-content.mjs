// Generates src/content.gen.ts (page metadata + nav tree) from content/docs.
// Runs outside Vite so no transform/discovery pitfalls; MDX components are still
// loaded lazily at runtime via import.meta.glob (see src/content.ts).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import GithubSlugger from "github-slugger";
import matter from "gray-matter";

const root = fileURLToPath(new URL("..", import.meta.url));
const contentDir = join(root, "content/docs");

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else if (name.endsWith(".mdx")) out.push(p);
  }
  return out;
}

const toGlobKey = (abs) => "/" + relative(root, abs).split("\\").join("/");

function fileToSlug(globKey) {
  const s = globKey.slice("/content/docs/".length).replace(/\.mdx$/, "");
  if (s === "index") return "";
  return s.replace(/\/index$/, "");
}

function extractToc(md) {
  const slugger = new GithubSlugger();
  const toc = [];
  let inFence = false;
  for (const line of md.split("\n")) {
    if (line.startsWith("```")) {
      inFence = !inFence;
      continue;
    }
    if (inFence) continue;
    const m = /^(#{2,3})\s+(.+?)\s*$/.exec(line);
    if (m) {
      const text = m[2].replace(/[*_`]/g, "").trim();
      toc.push({ depth: m[1].length, id: slugger.slug(text), text });
    }
  }
  return toc;
}

const pageMeta = walk(contentDir)
  .map((abs) => {
    const filePath = toGlobKey(abs);
    const { content, data } = matter(readFileSync(abs, "utf8"));
    const slug = fileToSlug(filePath);
    return {
      description: data.description ?? undefined,
      filePath,
      slug,
      title: data.title ?? slug ?? "Docs",
      toc: extractToc(content),
      type: data.type ?? undefined,
      url: slug ? `/docs/${slug}` : "/docs",
    };
  })
  .sort((a, b) => a.url.localeCompare(b.url));

function readMeta(dirGlob) {
  try {
    return JSON.parse(
      readFileSync(join(root, dirGlob.slice(1), "meta.json"), "utf8"),
    );
  } catch {
    return undefined;
  }
}

function buildTree(dir) {
  const meta = readMeta(`/content/docs${dir}`);
  const order = meta?.pages ?? [];
  const nodes = [];
  for (const entry of order) {
    const fileGlob = `/content/docs${dir}/${entry}.mdx`;
    const page = pageMeta.find((p) => p.filePath === fileGlob);
    if (page) {
      nodes.push({ title: page.title, url: page.url });
    } else {
      const subMeta = readMeta(`/content/docs${dir}/${entry}`);
      nodes.push({
        children: buildTree(`${dir}/${entry}`),
        title: subMeta?.title ?? entry,
      });
    }
  }
  return nodes;
}

const pageTree = buildTree("");

const out = `// GENERATED by scripts/gen-content.mjs (\`pnpm content:gen\`). Do not edit.
import type { PageMeta, TreeNode } from "./content";

export const pageMeta: PageMeta[] = ${JSON.stringify(pageMeta, null, 2)};

export const pageTree: TreeNode[] = ${JSON.stringify(pageTree, null, 2)};
`;

writeFileSync(join(root, "src/content.gen.ts"), out);
console.log(`generated src/content.gen.ts — ${pageMeta.length} pages`);
