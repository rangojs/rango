import { createHash } from "node:crypto";
import { isAbsolute, relative } from "node:path";
import { isAutoGeneratedRouteName } from "../../route-name.js";
import type {
  RouteCacheDeclaration,
  RouteInterceptDeclaration,
  RouteLoaderDeclaration,
  RouteKind,
  RouteOwnershipRecord,
  RouteRecord,
  RouteSegmentDeclaration,
  RouteStructureDeclaration,
  RouterRecord,
} from "../../devtools-mcp/protocol.js";
import type { EntryData, LoaderEntry } from "../../server/context.js";
import type { DiscoveryState } from "./state.js";
import type { RouteMatchIndex } from "../../devtools-mcp/snapshot-store.js";

const MAX_ROUTE_FIELD_LENGTH = 4_096;
const MAX_ROUTER_FIELD_LENGTH = 1_024;
const MAX_SEARCH_ENTRIES = 64;
const MAX_SEARCH_FIELD_LENGTH = 256;
const MAX_DECLARATION_ITEMS = 64;
const MAX_DECLARATION_TAGS = 16;

function bounded(value: string, limit: number): [string, boolean] {
  const encoded = Buffer.from(value, "utf8");
  if (encoded.byteLength <= limit) return [value, false];
  return [
    `${encoded
      .subarray(0, limit - 3)
      .toString("utf8")
      .replace(/\ufffd$/u, "")}...`,
    true,
  ];
}

function boundedRouterId(value: string): [string, boolean] {
  const encoded = Buffer.from(value, "utf8");
  if (encoded.byteLength <= MAX_ROUTER_FIELD_LENGTH) return [value, false];
  const suffix = `...#${createHash("sha256").update(encoded).digest("hex").slice(0, 12)}`;
  const prefix = encoded
    .subarray(0, MAX_ROUTER_FIELD_LENGTH - Buffer.byteLength(suffix))
    .toString("utf8")
    .replace(/\ufffd+$/u, "");
  return [`${prefix}${suffix}`, true];
}

function routeKind(pattern: string): RouteKind {
  if (pattern.includes("*")) return "wildcard";
  if (pattern.includes(":")) return "parameterized";
  return "static";
}

function ownValue(value: unknown, key: string): unknown {
  if (!value || (typeof value !== "object" && typeof value !== "function")) {
    return undefined;
  }
  try {
    return Object.getOwnPropertyDescriptor(value, key)?.value;
  } catch {
    return undefined;
  }
}

function finiteNumber(value: unknown): number | null {
  return typeof value === "number" && Number.isFinite(value) ? value : null;
}

function staticTags(value: unknown): {
  tags: string[];
  runtime: boolean;
  truncated: boolean;
} {
  if (typeof value === "function") {
    return { tags: [], runtime: true, truncated: false };
  }
  if (!Array.isArray(value)) {
    return { tags: [], runtime: false, truncated: value !== undefined };
  }
  const strings = value.filter(
    (item): item is string => typeof item === "string",
  );
  const tags = strings
    .slice(0, MAX_DECLARATION_TAGS)
    .map((tag) => bounded(tag, 256)[0]);
  return {
    tags,
    runtime: false,
    truncated:
      strings.length !== value.length ||
      strings.length > tags.length ||
      tags.some((tag, index) => tag !== strings[index]),
  };
}

const NO_CACHE_DECLARATION: RouteCacheDeclaration = {
  state: "none",
  ttl: null,
  swr: null,
  tags: [],
  tagsRuntime: false,
  keyRuntime: false,
  conditionRuntime: false,
  storeOverride: false,
  truncated: false,
};

function projectCacheDeclaration(
  cache: EntryData["cache"] | LoaderEntry["cache"],
): RouteCacheDeclaration {
  if (!cache) return { ...NO_CACHE_DECLARATION };
  const options = ownValue(cache, "options");
  if (options === false) {
    return { ...NO_CACHE_DECLARATION, state: "disabled" };
  }
  if (!options || typeof options !== "object") {
    return { ...NO_CACHE_DECLARATION, state: "configured", truncated: true };
  }
  const projectedTags = staticTags(ownValue(options, "tags"));
  return {
    state: "configured",
    ttl: finiteNumber(ownValue(options, "ttl")),
    swr: finiteNumber(ownValue(options, "swr")),
    tags: projectedTags.tags,
    tagsRuntime: projectedTags.runtime,
    keyRuntime: typeof ownValue(options, "key") === "function",
    conditionRuntime: typeof ownValue(options, "condition") === "function",
    storeOverride: ownValue(options, "store") !== undefined,
    truncated: projectedTags.truncated,
  };
}

function declarationIdentity(value: unknown): string | null {
  for (const key of ["$$id", "$id", "id"]) {
    const candidate = ownValue(value, key);
    if (typeof candidate === "string" && candidate.length > 0) {
      return bounded(candidate, MAX_ROUTE_FIELD_LENGTH)[0];
    }
  }
  const name = ownValue(value, "name");
  return typeof name === "string" && name.length > 0
    ? bounded(name, 256)[0]
    : null;
}

function projectLoaders(loaders: readonly LoaderEntry[]): {
  loaders: RouteLoaderDeclaration[];
  truncated: boolean;
} {
  const selected = loaders.slice(0, MAX_DECLARATION_ITEMS);
  return {
    loaders: selected.map((loader) => ({
      id: declarationIdentity(loader.loader),
      cache: projectCacheDeclaration(loader.cache),
      revalidationRuntime: loader.revalidate.length > 0,
    })),
    truncated: selected.length < loaders.length,
  };
}

function projectIntercepts(entry: EntryData): {
  intercepts: RouteInterceptDeclaration[];
  truncated: boolean;
} {
  const selected = entry.intercept.slice(0, MAX_DECLARATION_ITEMS);
  return {
    intercepts: selected.map((intercept) => {
      const loaders = projectLoaders(intercept.loader);
      return {
        slot: bounded(intercept.slotName, 256)[0],
        targetRoute: bounded(intercept.routeName, MAX_ROUTE_FIELD_LENGTH)[0],
        selection: intercept.when.length > 0 ? "runtime" : "always",
        middlewareCount: intercept.middleware.length,
        loaders: loaders.loaders,
        truncated: loaders.truncated,
      };
    }),
    truncated: selected.length < entry.intercept.length,
  };
}

function projectSegment(entry: EntryData): RouteSegmentDeclaration {
  const loaders = projectLoaders(entry.loader);
  const intercepts = projectIntercepts(entry);
  const slots = Object.keys(entry.parallel);
  const selectedSlots = slots
    .slice(0, MAX_DECLARATION_ITEMS)
    .map((slot) => bounded(slot, 256)[0]);
  const transition = entry.transition;
  const transitionWhen = ownValue(transition, "when");
  return {
    id: bounded(entry.id, MAX_ROUTE_FIELD_LENGTH)[0],
    type: entry.type,
    mountPath: entry.mountPath
      ? bounded(entry.mountPath, MAX_ROUTE_FIELD_LENGTH)[0]
      : null,
    cache: projectCacheDeclaration(entry.cache),
    middlewareCount: entry.middleware.length,
    revalidationRuntime: entry.revalidate.length > 0,
    loading: entry.loading !== undefined && entry.loading !== false,
    transition:
      transition === undefined
        ? "none"
        : typeof transitionWhen === "function" || Array.isArray(transitionWhen)
          ? "runtime"
          : "static",
    loaders: loaders.loaders,
    parallelSlots: selectedSlots,
    intercepts: intercepts.intercepts,
    truncated:
      loaders.truncated ||
      intercepts.truncated ||
      selectedSlots.length < slots.length,
  };
}

function projectPpr(entry: Extract<EntryData, { type: "route" }>) {
  const ppr = entry.ppr;
  if (!ppr) {
    return {
      enabled: false,
      ttl: null,
      swr: null,
      tags: [],
      tagsTruncated: false,
      runtimeConfig: false,
    };
  }
  if (ppr === true) {
    return {
      enabled: true,
      ttl: null,
      swr: null,
      tags: [],
      tagsTruncated: false,
      runtimeConfig: false,
    };
  }
  const projectedTags = staticTags(ownValue(ppr, "tags"));
  return {
    enabled: true,
    ttl: finiteNumber(ownValue(ppr, "ttl")),
    swr: finiteNumber(ownValue(ppr, "swr")),
    tags: projectedTags.tags,
    tagsTruncated: projectedTags.truncated,
    runtimeConfig: projectedTags.runtime,
  };
}

export function createMcpRouteDeclarationCollector(
  declarations: Record<string, RouteStructureDeclaration>,
): (
  entries: ReadonlyMap<string, EntryData>,
  inheritedAncestors: readonly EntryData[],
) => void {
  return (entries, inheritedAncestors): void => {
    for (const [routeKey, entry] of entries) {
      if (entry.type !== "route") continue;
      const localChain: EntryData[] = [];
      for (
        let current: EntryData | null = entry;
        current;
        current = current.parent
      ) {
        localChain.unshift(current);
      }
      if (localChain[0]?.parent === null) localChain.shift();
      const chain = [...inheritedAncestors, ...localChain];
      const selected = chain.slice(-MAX_DECLARATION_ITEMS);
      const segments = selected.map(projectSegment);
      const ppr = projectPpr(entry);
      declarations[routeKey] = {
        segments,
        ppr,
        prerender: entry.isPrerender === true,
        passthrough: entry.isPassthrough === true,
        responseType: entry.responseType ?? null,
        truncated:
          selected.length < chain.length ||
          segments.some((segment) => segment.truncated) ||
          ppr.tagsTruncated,
      };
    }
  };
}

function projectRelativeFile(
  projectRoot: string,
  sourceFile: string | undefined,
): string | null {
  if (!sourceFile) return null;
  const result = relative(projectRoot, sourceFile);
  if (result === "" || result.startsWith("..") || isAbsolute(result)) {
    return null;
  }
  return result.replaceAll("\\", "/");
}

export function createMcpRouteSnapshot(state: DiscoveryState): RouteRecord[] {
  const routes: RouteRecord[] = [];

  for (const router of state.perRouterManifests) {
    const projectedRouterFile = projectRelativeFile(
      state.projectRoot,
      router.sourceFile,
    );
    const routerFile =
      projectedRouterFile === null
        ? null
        : bounded(projectedRouterFile, MAX_ROUTER_FIELD_LENGTH);
    for (const [internalName, pattern] of Object.entries(
      router.routeManifest,
    )) {
      let truncated = routerFile?.[1] ?? false;
      const [routerId, routerIdTruncated] = boundedRouterId(router.id);
      const [routePattern, patternTruncated] = bounded(
        pattern,
        MAX_ROUTE_FIELD_LENGTH,
      );
      const routeName = isAutoGeneratedRouteName(internalName)
        ? null
        : bounded(internalName, MAX_ROUTE_FIELD_LENGTH);
      const searchEntries = Object.entries(
        router.routeSearchSchemas?.[internalName] ?? {},
      );
      const search = Object.fromEntries(
        searchEntries.slice(0, MAX_SEARCH_ENTRIES).map(([key, value]) => {
          const [boundedKey, keyTruncated] = bounded(
            key,
            MAX_SEARCH_FIELD_LENGTH,
          );
          const [boundedValue, valueTruncated] = bounded(
            value,
            MAX_SEARCH_FIELD_LENGTH,
          );
          truncated ||= keyTruncated || valueTruncated;
          return [boundedKey, boundedValue];
        }),
      );
      truncated ||=
        routerIdTruncated ||
        patternTruncated ||
        routeName?.[1] === true ||
        searchEntries.length > MAX_SEARCH_ENTRIES;
      routes.push({
        routerId,
        routerFile: routerFile?.[0] ?? null,
        name: routeName?.[0] ?? null,
        pattern: routePattern,
        kind: routeKind(pattern),
        trailingSlash: router.routeTrailingSlash?.[internalName] ?? null,
        search: searchEntries.length === 0 ? null : search,
        truncated,
      });
    }
  }

  return routes;
}

export function createMcpRouterSnapshot(state: DiscoveryState): RouterRecord[] {
  return state.perRouterManifests.map((router) => {
    const file = projectRelativeFile(state.projectRoot, router.sourceFile);
    return {
      id: boundedRouterId(router.id)[0],
      file: file === null ? null : bounded(file, MAX_ROUTER_FIELD_LENGTH)[0],
    };
  });
}

export function createMcpRouteMatchIndexes(
  state: DiscoveryState,
): RouteMatchIndex[] {
  return state.perRouterManifests.map((router) => {
    const declarations = router.mcpRouteDeclarations ?? {};
    const routes: RouteMatchIndex["routes"] = {};
    for (const [routeKey, pattern] of Object.entries(router.routeManifest)) {
      const searchEntries = Object.entries(
        router.routeSearchSchemas?.[routeKey] ?? {},
      );
      const search = Object.fromEntries(
        searchEntries
          .slice(0, MAX_SEARCH_ENTRIES)
          .map(([key, value]) => [
            bounded(key, MAX_SEARCH_FIELD_LENGTH)[0],
            bounded(value, MAX_SEARCH_FIELD_LENGTH)[0],
          ]),
      );
      const structure = declarations[routeKey] ?? null;
      routes[routeKey] = {
        name: isAutoGeneratedRouteName(routeKey)
          ? null
          : bounded(routeKey, MAX_ROUTE_FIELD_LENGTH)[0],
        pattern: bounded(pattern, MAX_ROUTE_FIELD_LENGTH)[0],
        search: searchEntries.length > 0 ? search : null,
        structure,
        truncated:
          structure?.truncated === true ||
          searchEntries.length > MAX_SEARCH_ENTRIES,
      };
    }
    return {
      routerId: boundedRouterId(router.id)[0],
      trie: state.perRouterTrieMap.get(router.id) ?? null,
      routes,
    };
  });
}

export function createMcpSourceOwnershipSnapshot(
  state: DiscoveryState,
): RouteOwnershipRecord[] {
  const ownership: RouteOwnershipRecord[] = [];
  for (const router of state.perRouterManifests) {
    const declarationFiles = router.routeSourceFiles ?? {};
    for (const [internalName, routePattern] of Object.entries(
      router.routeManifest,
    )) {
      const declarationFile = declarationFiles[internalName];
      const sourceFile = declarationFile ?? router.sourceFile;
      const projected = projectRelativeFile(state.projectRoot, sourceFile);
      ownership.push({
        routerId: boundedRouterId(router.id)[0],
        routeName: isAutoGeneratedRouteName(internalName)
          ? null
          : bounded(internalName, MAX_ROUTE_FIELD_LENGTH)[0],
        routePattern: bounded(routePattern, MAX_ROUTE_FIELD_LENGTH)[0],
        source:
          projected === null
            ? null
            : {
                file: bounded(projected, MAX_ROUTER_FIELD_LENGTH)[0],
                kind: "route",
                precision: declarationFile ? "declaration-file" : "router-file",
              },
      });
    }
  }
  return ownership;
}
