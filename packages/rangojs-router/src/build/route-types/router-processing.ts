function countPublicRouteEntries(source: string): number {
  const matches =
    source.matchAll(/^\s+(?:"([^"]+)"|([a-zA-Z_$][^:]*)):\s*["{]/gm) ?? [];
  let count = 0;
  for (const match of matches) {
    const routeName = match[1] || match[2];
    if (routeName && !isAutoGeneratedRouteName(routeName.trim())) {
      count++;
    }
  }
  return count;
}

const ROUTER_CALL_PATTERN = /\bcreateRouter\s*[<(]/;
// Global variant for the code-region scan (firstCodeMatchIndex sets lastIndex).
const ROUTER_CALL_PATTERN_G = /\bcreateRouter\s*[<(]/g;

function isRoutableSourceFile(name: string): boolean {
  return (
    (name.endsWith(".ts") ||
      name.endsWith(".tsx") ||
      name.endsWith(".js") ||
      name.endsWith(".jsx")) &&
    !name.includes(".gen.") &&
    !name.includes(".test.") &&
    !name.includes(".spec.")
  );
}

function isExcludedScanDir(name: string): boolean {
  return (
    name === "node_modules" ||
    name === "dist" ||
    name === "coverage" ||
    name === "__tests__" ||
    name === "__mocks__" ||
    name.startsWith(".")
  );
}

/**
 * Recursively collect source files whose code contains `pattern` (a comment- or
 * string-only mention is ignored via firstCodeMatchIndex). Shared by createRouter
 * and createHostRouter discovery, which differ only in the call pattern and
 * `stopAtMatchDir`: createRouter treats a directory containing a match as a router
 * root and stops descending it; createHostRouter descends the whole tree (the host
 * entry sits above the sub-app router roots).
 *
 * `pattern` is the non-global tester (no lastIndex state); `patternG` is its global
 * twin for the code-region scan.
 */
function findCallSiteFilesRecursive(
  dir: string,
  pattern: RegExp,
  patternG: RegExp,
  stopAtMatchDir: boolean,
  filter: ScanFilter | undefined,
  results: string[],
): void {
  let entries;
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch (err) {
    console.warn(
      `[rango] Failed to scan directory ${dir}: ${(err as Error).message}`,
    );
    return;
  }

  const childDirs: string[] = [];
  const matchesInDir: string[] = [];

  for (const entry of entries) {
    const fullPath = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (!isExcludedScanDir(entry.name)) childDirs.push(fullPath);
      continue;
    }

    if (!isRoutableSourceFile(entry.name)) continue;
    if (filter && !filter(fullPath)) continue;

    try {
      const source = readFileSync(fullPath, "utf-8");
      // Fast path: most files contain no `createRouter(` at all, so the cheap
      // raw regex short-circuits before the code-region scan. Only a file that
      // mentions the token (real call OR a comment/string mention) is rescanned
      // over code regions — allocation-free, never building a stripped copy —
      // so a mention inside a comment or string is not mistaken for a real
      // router file (which previously triggered a spurious "Multiple routers
      // found" error).
      if (pattern.test(source) && firstCodeMatchIndex(source, patternG) >= 0) {
        matchesInDir.push(fullPath);
      }
    } catch {
      continue;
    }
  }

  results.push(...matchesInDir);

  // createRouter (stopAtMatchDir): a directory that contains a match is a router
  // root, so deeper directories are skipped. createHostRouter: always descend.
  if (!stopAtMatchDir || matchesInDir.length === 0) {
    for (const childDir of childDirs) {
      findCallSiteFilesRecursive(
        childDir,
        pattern,
        patternG,
        stopAtMatchDir,
        filter,
        results,
      );
    }
  }
}

export function findNestedRouterConflict(
  routerFiles: string[],
): { ancestor: string; nested: string } | null {
  const routerDirs = [
    ...new Set(routerFiles.map((filePath) => dirname(resolve(filePath)))),
  ].sort((a, b) => a.length - b.length);

  for (let i = 0; i < routerDirs.length; i++) {
    const ancestorDir = routerDirs[i];
    const prefix = ancestorDir.endsWith(sep)
      ? ancestorDir
      : `${ancestorDir}${sep}`;
    for (let j = i + 1; j < routerDirs.length; j++) {
      const nestedDir = routerDirs[j];
      if (!nestedDir.startsWith(prefix)) continue;
      const ancestorFile = routerFiles.find(
        (filePath) => dirname(resolve(filePath)) === ancestorDir,
      );
      const nestedFile = routerFiles.find(
        (filePath) => dirname(resolve(filePath)) === nestedDir,
      );
      if (ancestorFile && nestedFile) {
        return { ancestor: ancestorFile, nested: nestedFile };
      }
    }
  }

  return null;
}

export function formatNestedRouterConflictError(
  conflict: { ancestor: string; nested: string },
  prefix = "[rango]",
): string {
  return (
    `${prefix} Nested router roots are not supported.\n` +
    `Router root: ${conflict.ancestor}\n` +
    `Nested router: ${conflict.nested}\n` +
    `Move the nested router into a sibling directory or configure it as a separate app root.`
  );
}

