import { basename, resolve } from "node:path";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import type { Plugin, PluginOption, ViteDevServer } from "vite";
import {
  generateRouteTypesSource,
  genFileTsPath,
  resolveSearchSchemas,
} from "./generate-route-types.ts";
import { mergeFullManifests } from "./merge-full-manifests.js";
import { isAutoGeneratedRouteName } from "../route-name.js";

export interface RuntimeDiscoveryOptions {
  /** Project root directory (where package.json / node_modules live). */
  root: string;
  /** Path to vite.config.ts. Auto-detected from root if omitted. */
  configFile?: string;
  /** Absolute path to the router entry file. */
  entry: string;
  /** Override resolve.alias (skips loading from vite config when provided). */
  resolveAlias?: Record<string, string>;
}

/**
 * Standalone Vite-based route discovery for the CLI.
 * Creates a temporary Vite server with the RSC plugin, imports the entry via
 * the module runner, reads the RouterRegistry, generates manifests, and writes
 * named-routes.gen.ts files.
 *
 * This mirrors the logic in the Vite plugin's discoverRouters() + writeRouteTypesFiles()
 * but without coupling to plugin closure state.
 */
export async function discoverAndWriteRouteTypes(
  opts: RuntimeDiscoveryOptions,
): Promise<{
  routerCount: number;
  routeCount: number;
  outputFiles: string[];
}> {
  let loadConfigFromFile: typeof import("vite").loadConfigFromFile;
  let resolveConfig: typeof import("vite").resolveConfig;

  try {
    const vite = await import("vite");
    loadConfigFromFile = vite.loadConfigFromFile;
    resolveConfig = vite.resolveConfig;
  } catch {
    throw new Error(
      "Runtime discovery requires 'vite'. Install it with: pnpm add -D vite",
    );
  }

  try {
    await import("@vitejs/plugin-rsc");
  } catch {
    throw new Error(
      "Runtime discovery requires '@vitejs/plugin-rsc'. Install it with: pnpm add -D @vitejs/plugin-rsc",
    );
  }

  const { createTempRscServer } = await import("../vite/temp-rsc-server.js");
  const { createDiscoveryState } = await import("../vite/discovery/state.js");
  const { discoverClientUrlProjections } =
    await import("../vite/discovery/client-urls-projection.js");
  const {
    isFrameworkPlugin,
    pickForwardedRunnerConfig,
    selectForwardableResolvePlugins,
  } = await import("../vite/utils/forward-user-plugins.js");

  // The discovery temp server of `vite dev/build` (expose-internal-ids, the
  // cloudflare:* stubs, the user's resolver plugins and resolve/define/oxc).
  // Resolver plugins are forwarded from a resolved config, as `vite dev` does:
  // vite-tsconfig-paths and the like build their matchers in config /
  // configResolved, and resolving drops `apply: "build"` plugins. The
  // framework plugins are left out of that resolve: rango()'s configResolved
  // writes the static gen files.
  const entryPath = resolve(opts.entry);
  const state = createDiscoveryState(entryPath, undefined);
  state.projectRoot = opts.root;
  state.userResolveAlias = opts.resolveAlias;
  if (!opts.resolveAlias) {
    try {
      const loaded = await loadConfigFromFile(
        { command: "serve", mode: "development" },
        opts.configFile,
        opts.root,
      );
      if (loaded) {
        state.userRunnerConfig = pickForwardedRunnerConfig(loaded.config);
        const userPlugins = (
          await flattenPluginOptions(loaded.config.plugins)
        ).filter((p) => !isFrameworkPlugin(p.name ?? ""));
        try {
          // The temp server's root, so a resolver's root-relative state
          // matches the server it runs in.
          const resolved = await resolveConfig(
            {
              ...loaded.config,
              root: opts.root,
              configFile: false,
              plugins: userPlugins,
            },
            "serve",
            "development",
          );
          state.userResolvePlugins = selectForwardableResolvePlugins(
            resolved.plugins,
          );
        } catch (err: any) {
          console.warn(
            `[rango] Could not resolve the Vite config (${err?.message ?? err}); forwarding its resolver plugins without their config hooks. rango() and rsc() are left out of that resolve, so a plugin that needs the rsc environment fails there`,
          );
          // The resolve would have applied `apply`; do the same for the serve
          // pass, including the function form.
          const serveEnv = { command: "serve", mode: "development" } as const;
          state.userResolvePlugins = selectForwardableResolvePlugins(
            userPlugins.filter((p) =>
              typeof p.apply === "function"
                ? p.apply(loaded.config, serveEnv)
                : p.apply !== "build",
            ),
          );
        }
      }
    } catch (err: any) {
      // Discovery without the app's resolvers fails later on an unrelated
      // import; name the cause here.
      console.warn(
        `[rango] Could not load the Vite config (${err?.message ?? err}); discovering without its resolve config and plugins`,
      );
    }
  }

  let tempServer: ViteDevServer | null = null;

  try {
    tempServer = await createTempRscServer(state, {
      cacheDir: "node_modules/.vite_rango_generate",
      plugins: [missingGenFileStubPlugin()],
    });

    const rscEnv = (tempServer.environments as any)?.rsc;
    if (!rscEnv?.runner) {
      throw new Error("RSC environment runner not available");
    }

    // Import the entry to trigger createRouter() registration
    await rscEnv.runner.import(entryPath);

    // Read the RouterRegistry
    const serverMod = await rscEnv.runner.import("@rangojs/router/server");
    const registry: Map<string, any> = serverMod.RouterRegistry;

    if (!registry || registry.size === 0) {
      throw new Error(
        `No routers found in registry after importing ${opts.entry}`,
      );
    }

    // include() of a clientUrls() module resolves from these projections.
    await discoverClientUrlProjections(
      state,
      (tempServer.environments as any)?.ssr,
      serverMod,
      rscEnv,
    );

    // Import build utilities for manifest generation
    const buildMod = await rscEnv.runner.import("@rangojs/router/build");
    const generateManifestFull = buildMod.generateManifestFull;

    if (!generateManifestFull) {
      throw new Error(
        "generateManifestFull not found in @rangojs/router/build",
      );
    }

    const outputFiles: string[] = [];
    let totalRouteCount = 0;
    let globalMountIndex = 0;
    let routerCount = 0;

    for (const [id, router] of registry) {
      const mounts =
        router.__urlpatternMounts ??
        (router.urlpatterns ? [{ patterns: router.urlpatterns }] : []);
      if (mounts.length === 0) continue;

      const mountManifests = [];
      for (const mount of mounts) {
        mountManifests.push(
          await generateManifestFull(
            mount.patterns,
            globalMountIndex,
            router.__basename ? { urlPrefix: router.__basename } : undefined,
          ),
        );
        globalMountIndex++;
      }
      const manifest = mergeFullManifests(mountManifests);
      routerCount++;

      // Filter out auto-generated route names that the runtime creates for
      // unnamed routes (path() with no name option). These get names like
      // "$path__health" at root level or "docs.$path__health" under include().
      // Match the Vite discovery writer's predicate: any name starting with "$"
      // is internal. For prefixed names, check each dot-separated segment.
      const rawManifest: Record<string, string> = manifest.routeManifest;
      const routeManifest: Record<string, string> = {};
      for (const [name, pattern] of Object.entries(rawManifest)) {
        if (!isAutoGeneratedRouteName(name)) {
          routeManifest[name] = pattern;
        }
      }
      let routeSearchSchemas:
        | Record<string, Record<string, string>>
        | undefined = manifest.routeSearchSchemas;

      // Determine output location from __sourceFile
      const sourceFile: string | undefined = router.__sourceFile;
      if (!sourceFile) {
        console.warn(
          `[rango] Router "${id}" has no __sourceFile, skipping gen file`,
        );
        continue;
      }

      // Guard against writing gen files into node_modules
      if (sourceFile.includes("node_modules")) {
        throw new Error(
          `[rango] Router "${id}" has sourceFile inside node_modules: ${sourceFile}\n` +
            `This means createRouter() stack trace parsing matched an internal frame.\n` +
            `Set an explicit \`id\` on createRouter() or check the call site.`,
        );
      }

      routeSearchSchemas = resolveSearchSchemas(
        Object.keys(routeManifest),
        routeSearchSchemas,
        sourceFile,
      );

      const outPath = genFileTsPath(sourceFile);

      const source = generateRouteTypesSource(
        routeManifest,
        routeSearchSchemas && Object.keys(routeSearchSchemas).length > 0
          ? routeSearchSchemas
          : undefined,
      );

      const existing = existsSync(outPath)
        ? readFileSync(outPath, "utf-8")
        : null;
      if (existing !== source) {
        writeFileSync(outPath, source);
      }

      const routeCount = Object.keys(routeManifest).length;
      totalRouteCount += routeCount;
      outputFiles.push(outPath);

      console.log(
        `[rango] Generated route types (${routeCount} routes) -> ${outPath}`,
      );
    }

    return {
      routerCount,
      routeCount: totalRouteCount,
      outputFiles,
    };
  } finally {
    if (tempServer) {
      await tempServer.close();
    }
  }
}

const MISSING_GEN_PREFIX = "\0rango-missing-named-routes-gen:";

/**
 * expose-router-id makes every createRouter() file import its sibling
 * `./<name>.named-routes.gen.js`. `vite dev/build` write those from static
 * parsing before discovery; the CLI does not, so a missing one resolves to an
 * empty NamedRoutes here and discovery writes the real file. An existing gen
 * file loads from disk as usual.
 */
function missingGenFileStubPlugin(): Plugin {
  return {
    name: "@rangojs/router:missing-gen-file-stub",
    enforce: "pre",
    resolveId(id, importer) {
      if (!importer || !id.endsWith(".named-routes.gen.js")) return null;
      const genPath = genFileTsPath(importer.split("?", 1)[0]);
      if (id !== `./${basename(genPath, ".ts")}.js` || existsSync(genPath)) {
        return null;
      }
      return MISSING_GEN_PREFIX + genPath;
    },
    load(id) {
      return id.startsWith(MISSING_GEN_PREFIX)
        ? "export const NamedRoutes = {};\n"
        : null;
    },
  };
}

/**
 * Flatten an unresolved `plugins` option (nested arrays, promises, falsy
 * entries) the way Vite's config resolution does, without running any hook.
 */
async function flattenPluginOptions(
  option: PluginOption | undefined,
): Promise<Plugin[]> {
  const value = await option;
  if (Array.isArray(value)) {
    return (await Promise.all(value.map(flattenPluginOptions))).flat();
  }
  return value ? [value as Plugin] : [];
}
