// Mutating Headers methods guarded so they throw inside "use cache" / cache()
// scope. Module-level constant (read-only, .has() lookups) so it is allocated
// once at module load instead of per createHandlerContext (per-request) call.
const MUTATING_HEADERS_METHODS = new Set(["set", "append", "delete"]);

/** The request context a handler ctx's `theme` getter reads (THEME_DESCRIPTOR). */
const THEME_REQUEST_CONTEXT = Symbol("rango:theme-request-context");

/**
 * ctx.theme is the visitor's theme cookie, guarded like cookies() (#971,
 * readGuardedTheme): a getter, so creating the ctx reads nothing and
 * only a handler that reads the theme refuses a ppr capture or throws on a
 * cache() miss. Non-enumerable, so serializing the ctx does not read it:
 * React's dev Flight debug info JSON-stringifies server component props and
 * replayed console.log args, and an enumerable getter read there refused the
 * capture of a route that never read the theme. The trade: a spread or
 * Object.assign copy of the ctx does not carry `theme`. One shared getter
 * with the request context on a symbol key: a getter closure per ctx gives
 * every ctx its own property shape (V8 dictionary mode). The guard reads the
 * ambient context, as cookies() does, and falls back to the ctx's own when
 * there is none.
 */
const THEME_DESCRIPTOR: PropertyDescriptor = {
  get(this: { [THEME_REQUEST_CONTEXT]?: RequestContext }) {
    return readGuardedTheme(this[THEME_REQUEST_CONTEXT], "ctx.theme");
  },
  enumerable: false,
  configurable: true,
};

/**
 * `headers` whose mutating methods run `assertWrite(method)` first. Shared by
 * the handler ctx (createHandlerContext) and the middleware ctx
 * (createMiddlewareContext).
 */
export function guardHeaderWrites(
  headers: Headers,
  assertWrite: (method: string | symbol) => void,
): Headers {
  return new Proxy(headers, {
    get(target, prop, receiver) {
      const value = Reflect.get(target, prop, receiver);
      if (typeof value === "function") {
        if (MUTATING_HEADERS_METHODS.has(prop as string)) {
          return (...args: any[]) => {
            assertWrite(prop);
            return value.apply(target, args);
          };
        }
        return value.bind(target);
      }
      return value;
    },
  });
}

