// Regenerates every per-module route-type file (`<module>.gen.ts`, the sibling
// `export const routes = {...} as const` of each `urls()` / `clientUrls()`
// module); with --check, verifies the committed copies are current.
//
// Why: the only writer of these files is the `rango generate` CLI
// (src/bin/rango.ts -> writePerModuleRouteTypesForFile). Vite dev and build
// write `router.named-routes.gen.ts`, never the per-module files, and nothing
// in CI or the hooks ran the CLI, so the committed copies drifted from their
// sources. `--check` is the CI freshness gate (`pnpm check:route-gen`).
//
// Inputs. Scan roots are `<dir>/src` of every package under apps/, examples/,
// tests/ and packages/rangojs-router/e2e/ whose package.json depends on
// `@rangojs/router`, so a new app needs no edit here. Sources are what
// `findTsFiles()` returns for those roots, the walk `rango generate <dir>` does.
// apps/docs/src/content.gen.ts has its own writer, apps/docs/scripts/
// gen-content.mjs, run here (with --check in check mode).
//
// Not the CLI. `rango generate <dir>` also builds `router.named-routes.gen.ts`
// and aborts with "Nested router roots are not supported" in the e2e test-app
// and examples/cloudflare-multi-router (several createRouter() files under one
// root). Per-module files do not depend on router detection, so the tool calls
// the router's per-module writer for each source file. Vite owns the
// named-routes files; they are out of scope.
//
// Loading the writer. The router is consumed from src/, so the tool bundles
// the plan function and its src imports with esbuild (a router devDependency)
// in memory, bare imports (typescript) left external and resolved from the
// router package; no `pnpm build-router` is needed. The plan function is pure
// (it reads sources, never writes), so the output is a function of the sources
// alone. Sources run in sorted order, two sources mapping to one `.gen.ts` fail
// the run, and reported paths are repo-relative with forward slashes. Sorting
// inside the generator is pinned to the "en" locale (codegen.ts), so the output
// does not depend on the machine's locale.
//
// Formatting. `.prettierignore` lists `*.gen.ts`, so oxfmt never touches these
// files and lefthook's format job excludes them. The writer's own output is the
// canonical form; running oxfmt over it would diverge from every other writer.
//
// Empty placeholders are skipped. A module whose `urls()` variable resolves to
// zero routes gets `routes = {}` from the CLI writer; committed, it asserts "no
// routes", which is false, and nothing imports it. Neither mode expects one; one
// found on disk is reported and deleted like an orphan.
//
// Partial maps. A module with both resolvable and unresolvable includes gets a
// map of the resolvable part only, the `rango generate --static` result. Three
// committed files are partial this way: the e2e test-app src/urls.tsx (the
// /factory-hmr factory), cloudflare-basic src/urls.tsx (the /docs import) and
// cloudflare-stress-demo src/urls.tsx (the /g hub's /g001-/g050, /mega,
// /dup/*). --verbose lists the modules whose includes were skipped.
//
// Orphans. A committed per-module file (generator header, not a
// `*.named-routes.gen.ts`) that no source produces any more, empty placeholders
// included, is reported by --check and deleted by the write mode.
//
// Run: node tools/generate-route-types.mjs            (regenerate, prune orphans)
//      node tools/generate-route-types.mjs --check    (exit 1 listing stale,
//                                                      missing and orphan files)
//      add --verbose to print the generator's non-fatal warnings and the
//      modules whose includes were skipped.

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const ROUTER_DIR = path.join(REPO_ROOT, "packages/rangojs-router");
const BUILD_DIR = path.join(ROUTER_DIR, "src/build/route-types");
const DOCS_CONTENT_SCRIPT = "apps/docs/scripts/gen-content.mjs";
const DOCS_CONTENT_FILE = "apps/docs/src/content.gen.ts";
// gen-content.mjs --check exits with this code for "stale"; 1 stays a crash.
const DOCS_STALE_EXIT = 3;

// Parents whose child packages are router consumers (apps, demos, e2e fixtures).
const APP_PARENTS = [
  "apps",
  "examples",
  "tests",
  "packages/rangojs-router/e2e",
];

// First line of every file the router's codegen writes; a `.gen.ts` without it
// belongs to another writer and is never pruned.
const GENERATED_HEADER = "// Auto-generated by @rangojs/router - do not edit";
const NAMED_ROUTES_SUFFIX = ".named-routes.gen.ts";

const args = new Set(process.argv.slice(2));
const CHECK = args.delete("--check");
const VERBOSE = args.delete("--verbose");
if (args.size > 0) {
  console.error(
    `Unknown argument: ${[...args].join(" ")}\nUsage: node tools/generate-route-types.mjs [--check] [--verbose]`,
  );
  process.exit(2);
}

const rel = (abs) => path.relative(REPO_ROOT, abs).split(path.sep).join("/");

const fail = (message) => {
  console.error(message);
  process.exit(2);
};

function discoverScanRoots() {
  const roots = [];
  for (const parent of APP_PARENTS) {
    const parentDir = path.join(REPO_ROOT, parent);
    if (!fs.existsSync(parentDir)) continue;
    const names = fs
      .readdirSync(parentDir, { withFileTypes: true })
      .filter((e) => e.isDirectory() && !e.name.startsWith("."))
      .map((e) => e.name)
      .sort();
    for (const name of names) {
      const dir = path.join(parentDir, name);
      const pkgPath = path.join(dir, "package.json");
      const srcDir = path.join(dir, "src");
      if (!fs.existsSync(pkgPath) || !fs.existsSync(srcDir)) continue;
      const pkg = JSON.parse(fs.readFileSync(pkgPath, "utf8"));
      const deps = {
        ...pkg.dependencies,
        ...pkg.devDependencies,
        ...pkg.peerDependencies,
      };
      if (deps["@rangojs/router"]) roots.push(srcDir);
    }
  }
  return roots;
}

async function loadGenerator() {
  const requireFromRouter = createRequire(
    path.join(ROUTER_DIR, "package.json"),
  );
  let esbuild;
  try {
    esbuild = requireFromRouter("esbuild");
  } catch {
    fail(
      "esbuild is not installed for @rangojs/router (a devDependency). Run `pnpm install`.",
    );
  }
  const { outputFiles } = await esbuild.build({
    stdin: {
      contents: `
        export { planPerModuleRouteTypesForFile } from "./per-module-writer.ts";
        export { findTsFiles, isSkippedSourceScanDir } from "./scan-filter.ts";
        export { detectUnresolvableIncludesForUrlsFile } from "./router-processing.ts";
      `,
      resolveDir: BUILD_DIR,
      sourcefile: "route-gen-entry.ts",
      loader: "ts",
    },
    bundle: true,
    packages: "external",
    platform: "node",
    format: "cjs",
    write: false,
    outfile: "route-gen.cjs",
    logLevel: "error",
  });
  const mod = { exports: {} };
  new Function("module", "exports", "require", outputFiles[0].text)(
    mod,
    mod.exports,
    requireFromRouter,
  );
  return mod.exports;
}

// Plans the per-module file of every source under the scan roots. Returns the
// files to write, keyed by absolute path.
function generate(gen, scanRoots) {
  const expected = new Map(); // abs gen path -> { content, source }
  const failures = [];
  const warnings = [];
  let skipped = 0; // empty placeholders, never expected
  const sources = scanRoots.flatMap((root) => gen.findTsFiles(root)).sort();

  let currentSource;
  const origWarn = console.warn;
  console.warn = (...parts) => {
    warnings.push(`${rel(currentSource)}: ${parts.join(" ")}`);
  };
  try {
    for (const source of sources) {
      currentSource = source;
      let plan;
      try {
        plan = gen.planPerModuleRouteTypesForFile(source);
      } catch (err) {
        failures.push(`${rel(source)}: ${err.message}`);
        continue;
      }
      if (!plan) continue;
      if (plan.isPlaceholder) {
        skipped++;
        continue;
      }
      const prior = expected.get(plan.genPath);
      if (prior) {
        failures.push(
          `${rel(source)} and ${rel(prior.source)} both map to ${rel(plan.genPath)}`,
        );
        continue;
      }
      expected.set(plan.genPath, { content: plan.content, source });
    }
  } finally {
    console.warn = origWarn;
  }
  return { expected, skipped, failures, warnings, sources };
}

// Committed per-module outputs: generator-headed `.gen.ts` files below the
// scan roots, minus the router-level named-routes files.
function findGeneratedFiles(gen, scanRoots) {
  const found = [];
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!gen.isSkippedSourceScanDir(entry.name)) walk(full);
      } else if (
        entry.name.endsWith(".gen.ts") &&
        !entry.name.endsWith(NAMED_ROUTES_SUFFIX) &&
        fs.readFileSync(full, "utf8").startsWith(GENERATED_HEADER)
      ) {
        found.push(full);
      }
    }
  };
  for (const root of scanRoots) walk(root);
  return found.sort();
}

function runDocsContent(check) {
  const file = path.join(REPO_ROOT, DOCS_CONTENT_FILE);
  const before = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
  const res = spawnSync(
    process.execPath,
    [path.join(REPO_ROOT, DOCS_CONTENT_SCRIPT), ...(check ? ["--check"] : [])],
    { encoding: "utf8" },
  );
  if (res.status !== 0 && !(check && res.status === DOCS_STALE_EXIT)) {
    console.error(res.stdout + res.stderr);
    return { error: `${DOCS_CONTENT_SCRIPT} failed (exit ${res.status})` };
  }
  if (check) {
    return {
      stale: res.status === DOCS_STALE_EXIT && before !== null,
      missing: before === null,
    };
  }
  const after = fs.readFileSync(file, "utf8");
  return {
    stale: before !== null && after !== before,
    created: before === null,
  };
}

// --verbose: modules whose includes the static parser skipped, so their map
// lists only the resolvable part (the `rango generate --static` result). The
// skipped includes are grouped per declaring file and reason.
function reportPartialMaps(gen, sources) {
  const partial = [];
  for (const source of sources) {
    const skipped = gen.detectUnresolvableIncludesForUrlsFile(source);
    if (skipped.length > 0) partial.push([source, skipped]);
  }
  console.log(
    `${partial.length} module(s) with skipped includes (partial map):`,
  );
  for (const [source, skipped] of partial) {
    console.log(`  ${rel(source)}`);
    const groups = new Map();
    for (const d of skipped) {
      const key = `${rel(d.sourceFile)} (${d.reason})`;
      groups.set(key, [...(groups.get(key) ?? []), d.pathPrefix]);
    }
    for (const [key, prefixes] of groups) {
      const shown = prefixes.slice(0, 3).join(", ");
      const more = prefixes.length > 3 ? `, +${prefixes.length - 3} more` : "";
      console.log(`    ${key}: ${shown}${more}`);
    }
  }
}

async function run() {
  const scanRoots = discoverScanRoots();
  if (scanRoots.length === 0) {
    fail("No app packages found to scan.");
  }
  const gen = await loadGenerator();
  const { expected, skipped, failures, warnings, sources } = generate(
    gen,
    scanRoots,
  );

  if (failures.length > 0) {
    console.error("Route type generation failed:");
    for (const f of failures) console.error(`  ${f}`);
    return 1;
  }
  if (expected.size === 0) {
    fail(
      `The generator produced no per-module files from ${sources.length} source file(s); refusing to ${CHECK ? "report" : "delete"} anything.`,
    );
  }
  if (VERBOSE) {
    for (const w of new Set(warnings)) console.warn(`warning: ${w}`);
    reportPartialMaps(gen, sources);
  }

  const stale = [];
  const missing = [];
  let unchanged = 0;
  for (const genPath of [...expected.keys()].sort()) {
    const { content } = expected.get(genPath);
    if (!fs.existsSync(genPath)) missing.push(genPath);
    else if (fs.readFileSync(genPath, "utf8") !== content) stale.push(genPath);
    else unchanged++;
  }
  // On-disk generated files no expected output covers: orphans, and empty
  // placeholders the CLI wrote for a source that still exists.
  const orphans = findGeneratedFiles(gen, scanRoots).filter(
    (p) => !expected.has(p),
  );
  if (!CHECK && orphans.length > expected.size) {
    fail(
      `Refusing to delete ${orphans.length} file(s) while generating only ${expected.size}; that looks like a broken generator, not a cleanup. Nothing was changed.`,
    );
  }
  const docs = runDocsContent(CHECK);

  const summary =
    `${sources.length} source file(s) scanned in ${scanRoots.length} app(s): ` +
    `${expected.size} per-module file(s), ${unchanged} current, ` +
    `${stale.length} stale, ${missing.length} missing, ${orphans.length} orphan`;

  if (CHECK) {
    const problems = [];
    const list = (title, files) => {
      if (files.length === 0) return;
      problems.push(`${title}:`);
      for (const f of files) problems.push(`  ${rel(f)}`);
    };
    list("Stale (differs from the generator output)", stale);
    list("Missing (the generator would create it)", missing);
    list("Orphan or empty placeholder (no source produces it)", orphans);
    if (docs.error) problems.push(docs.error);
    else if (docs.missing) {
      problems.push("Missing (own writer):", `  ${DOCS_CONTENT_FILE}`);
    } else if (docs.stale) {
      problems.push("Stale (own writer):", `  ${DOCS_CONTENT_FILE}`);
    }
    if (problems.length > 0) {
      console.error(`Generated route files are out of date. ${summary}\n`);
      console.error(problems.join("\n"));
      console.error(
        "\nRun `node tools/generate-route-types.mjs` and commit the result.",
      );
      return 1;
    }
    console.log(`Generated route files are current. ${summary}`);
    return 0;
  }

  for (const genPath of [...stale, ...missing]) {
    fs.writeFileSync(genPath, expected.get(genPath).content);
  }
  for (const p of orphans) fs.rmSync(p);
  const docsState = docs.created
    ? "created"
    : docs.stale
      ? "refreshed"
      : "unchanged";
  console.log(
    `${summary}\nwrote ${stale.length} refreshed, ${missing.length} new; ` +
      `removed ${orphans.length} orphan(s); ` +
      `${skipped} empty placeholder(s) skipped; ${DOCS_CONTENT_FILE} ${docsState}`,
  );
  if (docs.error) {
    console.error(docs.error);
    return 1;
  }
  return 0;
}

process.exit(await run());
