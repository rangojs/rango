// Generates packages/rangojs-router/skills/catalog.json — a machine-readable
// index (name/description/argument-hint/path) of every shipped skill.
//
// The package ships 43 agent skills but no way for a consumer's toolchain to
// discover them short of scanning SKILL.md frontmatter across 43 directories.
// This catalog is that index. It is generated, not hand-maintained: source of
// truth is the frontmatter block in each skills/<name>/SKILL.md.
//
// Frontmatter is parsed with a small hand-rolled single-line splitter (no
// YAML dependency) — every skill's name/description/argument-hint value is a
// single line between the `---` fences, so a generic YAML parser is not
// needed and would be a new dependency for zero benefit.
//
// --check also asserts bidirectional completeness against the hand-written
// catalog in skills/rango/SKILL.md's `## Skills` section: every skill
// directory (except `rango` itself, which is the catalog page and does not
// list itself) must appear as a `` `/name` `` table entry there, and every
// such entry must correspond to a real skill directory. That table's
// paraphrases are deliberately shorter than frontmatter descriptions and are
// NOT replaced or synced by this generator — only checked for completeness.
//
// Run: node tools/generate-skills-catalog.mjs          (writes the catalog)
//      node tools/generate-skills-catalog.mjs --check  (verify, exit 1 if stale)

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);

const SKILLS_DIR = path.join(REPO_ROOT, "packages/rangojs-router/skills");
const CATALOG_PATH = path.join(SKILLS_DIR, "catalog.json");
const RANGO_SKILL_PATH = path.join(SKILLS_DIR, "rango/SKILL.md");

// --- frontmatter parsing -----------------------------------------------------

// Parses the `--- ... ---` frontmatter block into a flat string map. Each
// field is `key: value` on its own line; values may be wrapped in double
// quotes (stripped) or bare (including empty, e.g. `argument-hint:`).
function parseFrontmatter(text) {
  const lines = text.split("\n");
  if (lines[0].trim() !== "---") {
    throw new Error("missing opening --- frontmatter fence");
  }
  const fields = {};
  let i = 1;
  for (; i < lines.length; i++) {
    const line = lines[i];
    if (line.trim() === "---") break;
    const colonIndex = line.indexOf(":");
    if (colonIndex === -1) continue;
    const key = line.slice(0, colonIndex).trim();
    let value = line.slice(colonIndex + 1).trim();
    if (value.startsWith('"') && value.endsWith('"') && value.length >= 2) {
      value = value.slice(1, -1);
    }
    fields[key] = value;
  }
  if (i === lines.length) {
    throw new Error("missing closing --- frontmatter fence");
  }
  return fields;
}

function loadSkills() {
  const dirNames = fs
    .readdirSync(SKILLS_DIR, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();

  const skills = [];
  for (const dirName of dirNames) {
    const skillPath = path.join(SKILLS_DIR, dirName, "SKILL.md");
    if (!fs.existsSync(skillPath)) continue;
    const text = fs.readFileSync(skillPath, "utf8");
    const fields = parseFrontmatter(text);
    if (!fields.name || !fields.description) {
      throw new Error(`${dirName}/SKILL.md is missing name or description`);
    }
    skills.push({
      name: fields.name,
      description: fields.description,
      argumentHint: fields["argument-hint"] ?? "",
      path: `skills/${dirName}/SKILL.md`,
    });
  }
  return skills;
}

// --- catalog rendering -------------------------------------------------------

function renderCatalog(skills) {
  const catalog = {
    "$schema-note":
      "Generated by tools/generate-skills-catalog.mjs — do not edit by hand.",
    package: "@rangojs/router",
    entry: "rango",
    skills,
  };
  return JSON.stringify(catalog, null, 2) + "\n";
}

// --- rango SKILL.md bidirectional completeness check -------------------------

// Extracts `/name` slugs from the `## Skills` ... next `## ` section of
// rango's SKILL.md, matching only real table-row entries of the form
// `| `/name` | ... |` (not incidental slashes inside description prose).
function extractRangoTableSlugs(text) {
  const startMarker = "\n## Skills\n";
  const startIndex = text.indexOf(startMarker);
  if (startIndex === -1) {
    throw new Error("rango/SKILL.md has no `## Skills` section");
  }
  const afterStart = startIndex + startMarker.length;
  const nextHeadingIndex = text.indexOf("\n## ", afterStart);
  const section = text.slice(
    afterStart,
    nextHeadingIndex === -1 ? text.length : nextHeadingIndex,
  );

  const slugs = new Set();
  const rowPattern = /^\|\s*`\/([a-z0-9-]+)`/gm;
  let match;
  while ((match = rowPattern.exec(section)) !== null) {
    slugs.add(match[1]);
  }
  return slugs;
}

function checkRangoCompleteness(skillNames) {
  const rangoText = fs.readFileSync(RANGO_SKILL_PATH, "utf8");
  const tableSlugs = extractRangoTableSlugs(rangoText);
  const dirSlugs = new Set(skillNames.filter((name) => name !== "rango"));

  const missingFromTable = [...dirSlugs].filter((s) => !tableSlugs.has(s));
  const missingFromDirs = [...tableSlugs].filter((s) => !dirSlugs.has(s));

  return { missingFromTable, missingFromDirs };
}

// --- run ----------------------------------------------------------------------

const checkMode = process.argv.includes("--check");

const skills = loadSkills();
const rendered = renderCatalog(skills);

if (checkMode) {
  let failed = false;

  const existing = fs.existsSync(CATALOG_PATH)
    ? fs.readFileSync(CATALOG_PATH, "utf8")
    : null;
  if (existing !== rendered) {
    console.error(
      "catalog.json is stale — run node tools/generate-skills-catalog.mjs",
    );
    failed = true;
  }

  const skillNames = skills.map((s) => path.basename(path.dirname(s.path)));
  const { missingFromTable, missingFromDirs } =
    checkRangoCompleteness(skillNames);
  if (missingFromTable.length > 0) {
    console.error(
      `skills/rango/SKILL.md ## Skills tables are missing: ${missingFromTable.join(", ")}`,
    );
    failed = true;
  }
  if (missingFromDirs.length > 0) {
    console.error(
      `skills/rango/SKILL.md ## Skills tables reference nonexistent skill dirs: ${missingFromDirs.join(", ")}`,
    );
    failed = true;
  }

  if (failed) process.exit(1);
  console.log(
    `Skills catalog guard: OK — catalog.json current, ${skills.length} skills, rango table complete both ways.`,
  );
} else {
  fs.writeFileSync(CATALOG_PATH, rendered);
  console.log(
    `Wrote ${path.relative(REPO_ROOT, CATALOG_PATH)} (${skills.length} skills).`,
  );
}
